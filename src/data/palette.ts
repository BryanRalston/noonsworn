export function mountPalette(target: HTMLElement) {
  const style = target.style
  const keys = Object.keys(HEX) as (keyof typeof HEX)[]
  for (let i = 0; i < keys.length; i++) {
    const key = keys[i]
    if (!key) continue
    style.setProperty('--' + key, HEX[key])
  }
}
